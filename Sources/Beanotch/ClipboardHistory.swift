import AppKit
import ImageIO
import Vision

struct ClipEntry: Identifiable {
    enum Content {
        case text(String)
        case image(NSImage, Data)
        case files([URL])
    }

    let id = UUID()
    let content: Content
    let date: Date
    var pinned = false
    // The app in front when it was copied.
    var source: String?
    // Text read out of an image, so screenshots can be searched by what they show.
    var recognized: String?

    var text: String? {
        if case .text(let s) = content { return s }
        return nil
    }

    // Everything a search can match: the text, what an image shows, the files' names.
    var searchable: String {
        switch content {
        case .text(let s): s
        case .image: recognized ?? ""
        case .files(let urls): urls.map(\.lastPathComponent).joined(separator: " ")
        }
    }

    func same(as other: Content) -> Bool {
        switch (content, other) {
        case (.text(let a), .text(let b)): a == b
        case (.image(_, let a), .image(_, let b)): a == b
        case (.files(let a), .files(let b)): a == b
        default: false
        }
    }
}

@MainActor
final class ClipboardHistory: ObservableObject {
    @Published private(set) var entries: [ClipEntry] = []
    @Published var enabled: Bool {
        didSet { UserDefaults.standard.set(enabled, forKey: "clipboardEnabled") }
    }

    var onText: ((String) -> Void)?
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    // What apps put on the pasteboard to say "don't keep this" (nspasteboard.org): secrets, and short-lived or
    // generated contents.
    private static let skipped: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    // Password managers and keychains, in case one doesn't mark what it copies.
    private static let ignoredApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop", "com.apple.keychainaccess",
        "com.apple.Passwords", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "in.sinew.Enpass-Desktop",
    ]

    var sorted: [ClipEntry] { entries.filter(\.pinned) + entries.filter { !$0.pinned } }

    init() {
        enabled = UserDefaults.standard.object(forKey: "clipboardEnabled") as? Bool ?? true
        entries = (UserDefaults.standard.stringArray(forKey: "clipboardPins") ?? [])
            .map { ClipEntry(content: .text($0), date: Date(), pinned: true) }
        let t = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        t.tolerance = 0.2
        timer = t
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard enabled else { return }
        let types = pb.types ?? []
        if types.contains(where: Self.skipped.contains) { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, Self.ignoredApps.contains(source) { return }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            insert(.files(urls), source: source)
        } else if let first = types.first, first == .tiff || first == .png, let image = Self.image(from: pb) {
            insert(.image(image.0, image.1), source: source)
        } else if let text = pb.string(forType: .string) {
            if !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                insert(.text(text), source: source)
                onText?(text)
            }
        } else if let image = Self.image(from: pb) {
            insert(.image(image.0, image.1), source: source)
        }
    }

    // Uncompressed TIFF from a Retina screen runs to tens of megabytes; it's kept as PNG instead.
    private static func image(from pb: NSPasteboard) -> (NSImage, Data)? {
        guard let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff), raw.count < 60_000_000,
              let image = NSImage(data: raw) else { return nil }
        if raw.count > 4_000_000, let rep = NSBitmapImageRep(data: raw),
           let png = rep.representation(using: .png, properties: [:]), png.count < raw.count {
            return (image, png)
        }
        return (image, raw)
    }

    private func insert(_ content: ClipEntry.Content, source: String?) {
        let pinned = entries.first { $0.same(as: content) }?.pinned ?? false
        entries.removeAll { $0.same(as: content) }
        let entry = ClipEntry(content: content, date: Date(), pinned: pinned, source: source)
        entries.insert(entry, at: 0)
        if let last = entries.lastIndex(where: { !$0.pinned }), entries.count(where: { !$0.pinned }) > 100 {
            entries.remove(at: last)
        }
        if case .image(_, let data) = content { recognize(data, for: entry.id) }
    }

    // On-device text recognition (Vision), off the main thread.
    private func recognize(_ data: Data, for id: UUID) {
        Task.detached(priority: .utility) {
            // ImageIO rather than NSImage: it's safe off the main thread, and the image is scaled down to read faster.
            let options = [kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: 2000] as CFDictionary
            guard let source = CGImageSourceCreateWithData(data as CFData, nil),
                  let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options) else { return }
            let request = VNRecognizeTextRequest()
            request.recognitionLevel = .accurate
            request.automaticallyDetectsLanguage = true
            try? VNImageRequestHandler(cgImage: image).perform([request])
            let text = (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }.joined(separator: " ")
            guard !text.isEmpty else { return }
            await MainActor.run {
                if let i = self.entries.firstIndex(where: { $0.id == id }) { self.entries[i].recognized = text }
            }
        }
    }

    func copy(_ entry: ClipEntry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch entry.content {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let image, _): pb.writeObjects([image])
        case .files(let urls): pb.writeObjects(urls as [NSURL])
        }
    }

    func togglePin(_ entry: ClipEntry) {
        guard let i = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[i].pinned.toggle()
        savePins()
    }

    func clear() {
        entries.removeAll { !$0.pinned }
    }

    // Pinned text is the only thing that outlives the app; everything else stays in memory.
    private func savePins() {
        UserDefaults.standard.set(entries.filter(\.pinned).compactMap(\.text), forKey: "clipboardPins")
    }

    // Plain substring first; failing that, the letters in order with gaps ("clpbrd" finds "clipboard").
    static func matches(_ text: String, _ query: String) -> Bool {
        if text.localizedCaseInsensitiveContains(query) { return true }
        var remaining = query.lowercased().filter { !$0.isWhitespace }[...]
        for character in text.lowercased() where character == remaining.first {
            remaining = remaining.dropFirst()
            if remaining.isEmpty { return true }
        }
        return remaining.isEmpty
    }
}
